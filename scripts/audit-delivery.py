"""Verify local research assets and deliverable links; no network requests."""
from datetime import date
from pathlib import Path
import hashlib
import json
import re
import subprocess
import argparse
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser()
parser.add_argument('--output', default='runs/final-audit.json')
args=parser.parse_args()
OUTPUT=(ROOT/args.output).resolve()
assert OUTPUT.is_relative_to(ROOT)
checks, errors, covered = [], [], set()
unique_hashes=set()


def walk_assets(value, parent):
    if isinstance(value, dict):
        if value.get('sha256'):
            name = value.get('file') or value.get('path') or value.get('local_path')
            if not name:
                errors.append(f'Hash without local file in {parent}')
            else:
                p = (parent / name).resolve()
                if not p.is_relative_to(parent.resolve()) or not p.is_file():
                    errors.append(f'Missing/outside asset {p}')
                else:
                    ok = hashlib.sha256(p.read_bytes()).hexdigest() == value['sha256']
                    if 'bytes' in value:
                        ok = ok and p.stat().st_size == value['bytes']
                    role=value.get('role','')
                    diagnostic=any(term in role for term in ['diagnostic','provisional','unverified_attribution'])
                    checks.append({'file': str(p.relative_to(ROOT)), 'hash_and_size': ok, 'diagnostic_or_provisional':diagnostic})
                    unique_hashes.add(value['sha256'])
                    covered.add(p)
                    if not ok:
                        errors.append(f'Hash/size mismatch {p}')
        for child in value.values():
            walk_assets(child, parent)
    elif isinstance(value, list):
        for child in value:
            walk_assets(child, parent)


case_root = ROOT / 'cases'
case_index = (case_root / 'README.md').read_text(encoding='utf-8-sig')
indexed_paths = set(re.findall(r'\[[^\]\n]+\]\(([^)\n]+)\)', case_index))
case_ids = set()
cases = []
for folder in sorted(path for path in case_root.iterdir() if path.is_dir()):
    manifest = folder / 'sources.json'
    report_path = folder / 'case.md'
    if not manifest.is_file() or not report_path.is_file():
        errors.append(f'{folder.name}: case.md and sources.json are both required')
        continue
    for path in (manifest, report_path):
        relative = path.relative_to(case_root).as_posix()
        if relative not in indexed_paths:
            errors.append(f'Missing case index entry: {relative}')
    data = json.loads(manifest.read_text(encoding='utf-8-sig'))
    case_id = data['case_id']
    if case_id in case_ids:
        errors.append(f'{folder.name}: duplicate case ID {case_id}')
    case_ids.add(case_id)
    walk_assets(data, folder)
    report = report_path.read_text(encoding='utf-8-sig')
    components = ['Key Screens', 'Experience Notes', 'Motion Specification', 'Interaction Flow']
    missing = [part for part in components if part not in report]
    if missing:
        errors.append(f'{folder.name}: missing {missing}')
    cases.append({'case': case_id, 'four_components': not missing})

media_suffixes = {'.png', '.jpg', '.jpeg', '.webp', '.gif', '.mp4'}
unregistered = [str(p.relative_to(ROOT)) for p in (ROOT / 'cases').rglob('*')
                if p.suffix.lower() in media_suffixes and p.resolve() not in covered]
if unregistered:
    errors.append(f'Unregistered case media: {unregistered}')

documents = list(ROOT.rglob('*.md'))
documents += [Path('D:/Dev/projects/project-console/README.md'),
              Path('D:/Dev/projects/project-console/.sites-checkout/planning/overall-plan.md')]
links = 0
for p in documents:
    for raw in re.findall(r'!?\[[^\]]*\]\(([^)]+)\)', p.read_text(encoding='utf-8-sig')):
        href = unquote(raw.strip('<>').split('#')[0])
        if not href or re.match(r'^(https?|obsidian|plugin|codex):', href) or '<' in href:
            continue
        target = Path(href) if re.match(r'^[A-Za-z]:[/\\]', href) else p.parent / href
        links += 1
        # This report is generated by this invocation.
        if target.resolve() == OUTPUT:
            continue
        if not target.exists():
            errors.append(f'Broken link {p}: {raw}')

scripts = list((ROOT / 'applications').rglob('*.js')) + list((ROOT / 'scripts').glob('*.mjs'))
for p in scripts:
    result = subprocess.run(['node', '--check', str(p)], capture_output=True, text=True)
    if result.returncode:
        errors.append(f'Syntax {p}: {result.stderr}')

font = ROOT / 'applications/project-console/prototypes/assets/Saira.ttf'
font_origin = Path('D:/Dev/projects/project-console/.sites-checkout/public/fonts')
font_matches = [str(p) for p in font_origin.glob('*.ttf')
                if hashlib.sha256(p.read_bytes()).digest() == hashlib.sha256(font.read_bytes()).digest()]
if not font_matches:
    errors.append('Prototype font does not match any existing product TTF')

record = {'date': date.today().isoformat(), 'method': 'case index coverage, local SHA256/size, component headings, link targets, node syntax; no source truth or human UX claim',
          'cases': cases, 'media_records_checked': len(checks), 'unique_sha256_contents':len(unique_hashes),
          'diagnostic_or_provisional_records':sum(c['diagnostic_or_provisional'] for c in checks),
          'counting_limit':'Records and distinct hashes do not count independent observations, workflows or source families', 'assets': checks,
          'unregistered_case_media': unregistered, 'local_links_checked': links,
          'javascript_files_checked': len(scripts), 'font_matches_product_source': font_matches,
          'errors': errors, 'passed': not errors}
OUTPUT.parent.mkdir(parents=True,exist_ok=True)
OUTPUT.write_text(json.dumps(record, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
print(json.dumps({k: v for k, v in record.items() if k not in ('assets', 'cases')}, ensure_ascii=False))
raise SystemExit(bool(errors))
