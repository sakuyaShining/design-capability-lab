import assert from 'node:assert/strict';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';

const workbench = new URL('../applications/project-console/workbench/', import.meta.url);
const folder = new URL('tasks/', workbench);
const script = readFileSync(new URL('../prototypes/data.js', workbench), 'utf8');
const seed = runInNewContext(script + '\nwindow.DEMO_TASKS;', { window: {} });
const byId = new Map(seed.map(task => [task.id, task.code]));
const prerequisites = new Map(seed.map(({ code, deps }) => [code, Array.from(deps, id => byId.get(id))]));
prerequisites.set('PC-01', []);
prerequisites.set('PC-02', ['PC-01']);
const pilot = JSON.parse(readFileSync(new URL('../runs/project-workbench/task-entry/record.json', import.meta.url), 'utf8'));
const codes = readdirSync(folder, { withFileTypes: true }).filter(entry => entry.isDirectory()).map(entry => entry.name);
assert.deepEqual([...codes].sort(), [...prerequisites.keys()].sort(), 'Expected one README directory per workbench task.');

const escape = value => value.replace(/[&<>"']/g, char =>
  ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);

function readGraph(chart, code) {
  const nodes = new Map();
  const edges = [];
  const lines = chart.trim().split(/\r?\n/).map(line => line.trim());
  assert.equal(lines.shift(), 'flowchart LR', code);
  for (const line of lines.filter(Boolean)) {
    const node = line.match(/^(\w+)\["([^"]+)"\]$/);
    const edge = line.match(/^(\w+) --> (\w+)$/);
    assert.ok(node || edge, `${code}: unsupported diagram line ${line}`);
    if (node) {
      const [, id, label] = node;
      assert.ok(!nodes.has(id), `${code}: duplicate node ${id}`);
      nodes.set(id, { id, label, deps: [] });
    } else {
      edges.push(edge.slice(1));
    }
  }
  for (const [from, to] of edges) {
    assert.ok(nodes.has(from) && nodes.has(to), `${code}: unknown step in ${from} → ${to}`);
    nodes.get(to).deps.push(from);
  }
  assert.ok(nodes.size, `${code}: empty graph`);
  const layers = [];
  const remaining = new Set(nodes.keys());
  while (remaining.size) {
    const layer = [...remaining].map(id => nodes.get(id)).filter(node => node.deps.every(id => !remaining.has(id)));
    assert.ok(layer.length, `${code}: cyclic steps`);
    for (const node of layer) remaining.delete(node.id);
    layers.push(layer);
  }
  const allAdjacent = layers.slice(1).every((layer, index) =>
    layer.every(node => node.deps.length === layers[index].length && layers[index].every(prev => node.deps.includes(prev.id))));
  return { layers, allAdjacent, nodes };
}

function readDoc(code) {
  const file = new URL(`${code}/README.md`, folder);
  const raw = readFileSync(file, 'utf8');
  const [heading, ...sections] = raw.trim().split(/^## /m);
  const title = heading.trim().slice(('# ' + code + ' ').length);
  assert.ok(heading.startsWith('# ' + code + ' ') && title, code);
  const fields = new Map(sections.map(section => {
    const [name, ...body] = section.split(/\r?\n/);
    return [name, body.join('\n').trim()];
  }));
  const deps = [...fields.get('跨任务前置').matchAll(/^- \[([\w-]+)\]\(\.\.\/\1\/README\.md\)$/gm)].map(match => match[1]);
  assert.deepEqual(deps, prerequisites.get(code), `${code}: README prerequisites disagree with the task data.`);
  const chart = fields.get('执行步骤').match(/^```mermaid\s+([\s\S]+?)\s*```$/m);
  assert.ok(chart, `${code}: missing Mermaid diagram`);
  const links = [...(fields.get('相关资料') || '').matchAll(/^- \[([^\]]+)\]\(([^)]+)\)$/gm)].map(match => {
    const [, label, href] = match;
    readFileSync(new URL(href, file));
    return { label, href };
  });
  return {
    code, title, deps, links,
    about: fields.get('任务说明'),
    output: fields.get('交付标准'),
    graph: readGraph(chart[1], code),
  };
}

const docs = [...prerequisites.keys()].map(readDoc);
const titleByCode = new Map(docs.map(({ code, title }) => [code, title]));

function page(title, from, content) {
  return `<!doctype html>
<!-- Generated by scripts/build-task-readmes.mjs. Edit the corresponding README.md. -->
<html lang="zh-CN" data-ef-accent="ice">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escape(title)} | 项目总控台</title>
  <link rel="stylesheet" href="${from}style.css">
  <link rel="stylesheet" href="${from}task-docs.css">
</head>
<body>
  <header class="command">
    <div class="shell command-bar">
      <a class="brand" href="${from}index.html"><i aria-hidden="true"></i><span><small>PROJECT CONSOLE</small><b>项目总控台</b></span></a>
      <nav aria-label="入口"><a href="${from}index.html">工作台</a><a href="${from}tasks/index.html">任务总览</a></nav>
    </div>
  </header>
  <main class="shell">${content}</main>
</body>
</html>
`;
}

function taskLink(code, prefix) {
  return `<a class="doc-task-link" href="${prefix}${code}/index.html"><b class="code">${code}</b><span>${escape(titleByCode.get(code))}</span></a>`;
}

function diagram({ layers, allAdjacent, nodes }) {
  return `<ol class="doc-flow${allAdjacent ? ' connected' : ''}" aria-label="任务执行步骤" style="--stages:${layers.length}">
      ${layers.map(layer => `<li class="doc-stage"><ul class="stage-nodes${layer.length === 2 ? ' branch' : ''}">
        ${layer.map(node => `<li><strong>${escape(node.label)}</strong>${
          !allAdjacent && node.deps.length ? `<small>依赖 ${escape(node.deps.map(id => nodes.get(id).label).join('、'))}</small>` : ''
        }</li>`).join('\n        ')}
      </ul></li>`).join('\n      ')}
    </ol>`;
}

function trialSnapshot(code) {
  if (!pilot.result || !code.startsWith('PC-')) return '';
  const upstream = code === 'PC-01';
  const { finding, revision } = pilot.result;
  return `<section class="doc-section doc-snapshot" aria-labelledby="snapshot">
      <h2 id="snapshot">${upstream ? 'PC-01 已提交结论' : 'PC-01 的交付结果'}</h2>
      <p>${escape(finding)}</p>
      <p class="meta">本机试点快照 · Git ${escape(revision.slice(0, 7))} · ${upstream ? 'PC-01 已完成' : 'PC-02 待开始，前置结果可用'}</p>
      ${taskLink(upstream ? 'PC-02' : 'PC-01', '../')}
    </section>`;
}

for (const doc of docs) {
  const { code, title, about, graph, deps, output, links } = doc;
  const interactive = links.find(link => link.href === 'archify.html');
  const references = links.filter(link => link !== interactive);
  const related = deps.length
    ? `<ul class="doc-links">${deps.map(dep => `<li>${taskLink(dep, '../')}</li>`).join('')}</ul>`
    : '<p>无直接前置任务。</p>';
  const supplemental = references.length
    ? `<section class="doc-section"><h2>相关资料</h2><ul class="doc-references">${references.map(({ label, href }) => `<li><a href="${escape(href)}">${escape(label)}</a></li>`).join('')}</ul></section>` : '';
  const interactiveLink = interactive
    ? `<a class="cut doc-interactive" href="${escape(interactive.href)}" target="_blank" rel="noopener">独立打开 ↗</a>`
    : '';
  const stepMap = `${diagram(graph)}
        <p class="meta">${graph.allAdjacent ? '沿箭头推进。同组步骤可并行，汇合后再进行下一步。' : '同组步骤可并行，每个步骤注明了它的前置。'}</p>`;
  const steps = interactive
    ? `<iframe class="diagram-frame" src="${escape(interactive.href)}?embed=1&amp;theme=light" title="${code} 任务步骤与依赖" loading="lazy"></iframe>
        <details class="doc-flow-fallback"><summary>查看简图</summary>${stepMap}</details>`
    : stepMap;
  const body = `
    <header class="doc-title">
      <div><p class="task-meta"><span class="code">${code}</span><span>${code.startsWith('PC-') ? '任务入口试点' : '任务说明样例'}</span></p>
        <h1>${escape(title)}</h1><p>${escape(about)}</p></div>
      <a class="cut" href="README.md">查看 README 原件</a>
    </header>
    <div class="doc-board">
      <section class="doc-section doc-steps" aria-labelledby="steps">
        <div class="doc-section-title"><h2 id="steps">任务内的步骤依赖</h2>${interactiveLink}</div>
        ${steps}
      </section>
      <div class="doc-support">
        <section class="doc-section"><h2>跨任务前置</h2>${related}</section>
        <section class="doc-section"><h2>交付标准</h2><p>${escape(output)}</p></section>
      </div>
      ${trialSnapshot(code)}
      ${supplemental}
    </div>`;
  writeFileSync(new URL(`${code}/index.html`, folder), page(`${code} ${title}`, '../../', body));
}

const groups = [
  ['任务入口试点', docs.filter(doc => doc.code.startsWith('PC-'))],
  ['工作台样例任务', docs.filter(doc => doc.code.startsWith('T-'))],
];
const index = `
    <header class="doc-title"><div><h1>任务总览</h1><p>打开任务，查看执行步骤、前置依赖和交付标准。</p></div></header>
    <div class="doc-board">${groups.map(([label, items]) =>
      `<section class="doc-section"><h2>${label}</h2><ul class="doc-catalog">${items.map(({ code }) =>
        `<li>${taskLink(code, './')}</li>`).join('')}</ul></section>`).join('\n    ')}</div>`;
writeFileSync(new URL('index.html', folder), page('任务总览', '../', index));
console.log(`Generated ${docs.length} task pages and one index from their README files.`);
